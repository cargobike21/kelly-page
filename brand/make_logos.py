#!/usr/bin/env python3
"""Generate the Kelly Page logo family (kelly-page/assets/*.svg) from one drawing.

The mark is a working dog in profile, ear up, listening -- amber signal arcs
behind the ear. Slate coat, amber eye, tan brow point, white chest blaze.

    .venv\\Scripts\\python.exe kelly-page\\brand\\make_logos.py

Edit the shapes or PALETTE here, never the generated SVGs.
"""
from pathlib import Path

ASSETS = Path(__file__).resolve().parent.parent / "assets"

PALETTE = {
    "navy": "#0F1D31", "navy_deep": "#0A1422", "slate_hi": "#768696", "slate_lo": "#4C5A6A",
    "slate_dark": "#3B4757", "amber": "#E8A33A", "tan": "#C98A4B", "white": "#F2F4F7",
    "ink": "#141B26", "text_light": "#F2F4F7", "text_dark": "#0F1D31", "muted": "#8A99AD",
}
P = PALETTE
FONT = "'Segoe UI', 'Helvetica Neue', Arial, sans-serif"

# Kelly's head in a 200x200 frame (faces right).
HEAD = f"""
    <path d="M 104 88 L 113 54 Q 117 46 122 53 L 132 84 Z" fill="{P['slate_dark']}"/>
    <path fill="url(#coat)" d="M 34 200 C 32 162 38 132 52 114 L 56 104 L 60 54 Q 64 42 73 49 L 98 88
      C 108 80 122 78 132 84 C 138 88 142 92 148 94 L 172 101 C 185 104 187 119 177 123 L 164 127
      C 154 135 142 139 130 139 C 116 141 106 149 100 163 C 96 174 96 188 98 200 Z"/>
    <path d="M 64 62 Q 66 56 70 60 L 88 88 L 68 96 Z" fill="{P['slate_dark']}" opacity=".55"/>
    <ellipse cx="128" cy="91" rx="6.5" ry="3.8" fill="{P['tan']}" transform="rotate(-10 128 91)"/>
    <ellipse cx="136" cy="102" rx="6.6" ry="4.6" fill="{P['amber']}" transform="rotate(-12 136 102)"/>
    <circle cx="137.6" cy="101.6" r="2.5" fill="{P['ink']}"/>
    <circle cx="138.6" cy="100.4" r=".9" fill="#FFFFFF" opacity=".8"/>
    <path d="M 175 102 C 185 103 188 114 182 120 C 177 123 170 120 168 113 C 167 107 169 102 175 102 Z" fill="{P['ink']}"/>
    <path d="M 166 127 C 158 133 148 135 140 134" fill="none" stroke="#2A3442" stroke-width="2.6" stroke-linecap="round"/>
    <path d="M 98 200 C 96 186 98 172 104 162 C 112 176 118 190 128 200 Z" fill="{P['white']}"/>"""

# Three arcs centred behind her head (angles 200-250 deg, y down).
ARCS = f"""
    <g fill="none" stroke="{P['amber']}" stroke-linecap="round" stroke-width="7.5">
      <path d="M 33.7 74.4 A 28 28 0 0 1 50.4 57.7"/>
      <path d="M 19.6 69.3 A 43 43 0 0 1 45.3 43.6" opacity=".68"/>
      <path d="M 5.5 64.2 A 58 58 0 0 1 40.2 29.5" opacity=".38"/>
    </g>"""


def defs(prefix=""):
    return f"""<defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#16263D"/><stop offset="1" stop-color="{P['navy_deep']}"/></linearGradient>
    <linearGradient id="coat" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{P['slate_hi']}"/><stop offset="1" stop-color="{P['slate_lo']}"/></linearGradient>
  </defs>"""


def svg(view, w, h, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{w}" height="{h}" role="img" aria-label="{title}">\n'
            f"  <title>{title}</title>\n  <!-- Generated by kelly-page/brand/make_logos.py: edit that, not this file. -->\n  {body}\n</svg>\n")


def app_icon():
    body = f"""{defs()}
  <clipPath id="clip"><rect width="200" height="200" rx="44"/></clipPath>
  <rect width="200" height="200" rx="44" fill="url(#bg)"/>
  <g clip-path="url(#clip)">{ARCS}{HEAD}
  </g>"""
    return svg("0 0 200 200", 200, 200, body, "Kelly Page")


def emblem():
    # circle badge with an amber hairline ring
    body = f"""{defs()}
  <clipPath id="clip"><circle cx="100" cy="100" r="92"/></clipPath>
  <circle cx="100" cy="100" r="99" fill="{P['navy_deep']}"/>
  <circle cx="100" cy="100" r="95.5" fill="none" stroke="{P['amber']}" stroke-width="2.5"/>
  <circle cx="100" cy="100" r="92" fill="url(#bg)"/>
  <g clip-path="url(#clip)"><g transform="translate(12 8) scale(.9)">{ARCS}{HEAD}
  </g></g>"""
    return svg("0 0 200 200", 200, 200, body, "Kelly Page")


def favicon():
    # tight crop for 16-32 px: bigger head, one bold arc
    body = f"""{defs()}
  <clipPath id="clip"><rect width="200" height="200" rx="40"/></clipPath>
  <rect width="200" height="200" rx="40" fill="url(#bg)"/>
  <g clip-path="url(#clip)"><g transform="translate(-20 -38) scale(1.16)">{HEAD}
    <path d="M 33.7 74.4 A 28 28 0 0 1 50.4 57.7" fill="none" stroke="{P['amber']}" stroke-width="11" stroke-linecap="round"/>
  </g></g>"""
    return svg("0 0 200 200", 64, 64, body, "Kelly Page")


def mono(color="#FFFFFF"):
    # single colour: silhouette + arcs, eye knocked out
    head = f"""<path fill="{color}" d="M 34 200 C 32 162 38 132 52 114 L 56 104 L 60 54 Q 64 42 73 49 L 98 88 L 104 88 L 113 54 Q 117 46 122 53 L 132 84
      C 138 88 142 92 148 94 L 172 101 C 185 104 187 119 177 123 L 164 127 C 154 135 142 139 130 139 C 116 141 106 149 100 163 C 96 174 96 188 98 200 Z"/>
    <ellipse cx="136" cy="102" rx="6.6" ry="4.6" fill="#000" transform="rotate(-12 136 102)"/>"""
    arcs = ARCS.replace(P["amber"], color)
    body = f"""<mask id="m"><rect width="200" height="200" fill="#fff"/><ellipse cx="136" cy="102" rx="6.6" ry="4.6" fill="#000" transform="rotate(-12 136 102)"/></mask>
  <g mask="url(#m)">{arcs}{head.split('<ellipse')[0]}</g>"""
    return svg("0 0 200 200", 200, 200, body, "Kelly Page")


def lockup(dark_bg=True):
    txt = P["text_light"] if dark_bg else P["text_dark"]
    sub = P["muted"] if dark_bg else "#56657A"
    accent = P["amber"] if dark_bg else "#B5701A"   # deeper amber keeps contrast on white
    body = f"""{defs()}
  <clipPath id="clip"><rect width="200" height="200" rx="44"/></clipPath>
  <g transform="scale(.6)"><rect width="200" height="200" rx="44" fill="url(#bg)"/><g clip-path="url(#clip)">{ARCS}{HEAD}</g></g>
  <text x="140" y="64" font-family="{FONT}" font-size="50" font-weight="700" letter-spacing="2" fill="{txt}">KELLY<tspan fill="{accent}" dx="14">PAGE</tspan></text>
  <rect x="142" y="80" width="40" height="3" rx="1.5" fill="{accent}"/>
  <text x="142" y="106" font-family="{FONT}" font-size="15" font-weight="600" letter-spacing="5" fill="{sub}">P25 RADIO CONSOLE</text>"""
    return svg("0 0 460 120", 460, 120, body, "Kelly Page -- P25 radio console")


FILES = {
    "kelly-mark.svg": app_icon(), "kelly-logo.svg": emblem(), "kelly-favicon.svg": favicon(),
    "kelly-mono.svg": mono(), "kelly-wordmark.svg": lockup(True), "kelly-wordmark-light.svg": lockup(False),
}

if __name__ == "__main__":
    for name, text in FILES.items():
        (ASSETS / name).write_text(text, encoding="utf-8", newline="\n")
        print("wrote", ASSETS / name)
